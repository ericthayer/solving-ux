// Reads every pattern folder (src/patterns/<category>/<slug>/) and writes two typed modules:
// - sources.generated.ts: raw component, stylesheet, and test source, so the Code and Tests
//   tabs, ZIP export, and JSON export stay in sync with the files that actually run.
// - catalog.generated.ts: imports of each folder's pattern, transcript, and walkthrough.
// With VITE_CLIENT set (scripts/build-clients.mjs), both only include that client's patterns,
// so another client's content never reaches the bundle.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../src/patterns/', import.meta.url).pathname;
const out = join(root, 'sources.generated.ts');
const catalogOut = join(root, 'catalog.generated.ts');
const CLIENT_IDS = ['client-a', 'client-b'];
const client = process.env.VITE_CLIENT || '';
if (client && !CLIENT_IDS.includes(client)) throw new Error(`Unknown VITE_CLIENT "${client}". Expected one of ${CLIENT_IDS.join(', ')}.`);

const entries = [];
const catalog = [];

/** Name of the first `export const X` in a module, or null when the file does not exist. */
function exportName(file) {
  if (!existsSync(file)) return null;
  const match = /export const (\w+)/.exec(readFileSync(file, 'utf8'));
  if (!match) throw new Error(`${relative(root, file)} needs an exported const.`);
  return match[1];
}

/** The `clients: [...]` list in a pattern.ts, so folders can be filtered without executing TS. */
function clientsOf(file) {
  const match = /clients:\s*\[([^\]]*)\]/.exec(readFileSync(file, 'utf8'));
  const ids = match ? [...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]) : [];
  if (ids.length === 0 || ids.some((id) => !CLIENT_IDS.includes(id))) {
    throw new Error(`${relative(root, file)} needs clients: [...] with ids from ${CLIENT_IDS.join(', ')}.`);
  }
  return ids;
}

for (const category of readdirSync(root)) {
  const categoryDir = join(root, category);
  if (!statSync(categoryDir).isDirectory()) continue;
  for (const slug of readdirSync(categoryDir)) {
    const dir = join(categoryDir, slug);
    if (!statSync(dir).isDirectory()) continue;
    const files = readdirSync(dir);
    const component = files.find((f) => /^[A-Z].*\.tsx$/.test(f) && !f.endsWith('.test.tsx'));
    const styles = files.find((f) => f.endsWith('.module.css'));
    const test = files.find((f) => f.endsWith('.test.tsx'));
    if (!component || !test) {
      throw new Error(`Pattern folder ${relative(root, dir)} needs a component and a test file.`);
    }
    const patternFile = join(dir, 'pattern.ts');
    if (!existsSync(patternFile)) throw new Error(`Pattern folder ${relative(root, dir)} needs a pattern.ts.`);
    if (client && !clientsOf(patternFile).includes(client)) continue;
    catalog.push({
      key: `${category}/${slug}`,
      pattern: exportName(patternFile),
      transcript: exportName(join(dir, 'transcript.ts')),
      walkthrough: exportName(join(dir, 'walkthrough.ts')),
    });
    const read = (f) => (f ? readFileSync(join(dir, f), 'utf8') : '');
    entries.push({
      key: `${category}/${slug}`,
      componentFile: component,
      component: read(component),
      stylesFile: styles ?? '',
      styles: read(styles),
      testFile: test,
      test: read(test),
    });
  }
}

const body = entries
  .sort((a, b) => a.key.localeCompare(b.key))
  .map((e) => `  ${JSON.stringify(e.key)}: ${JSON.stringify({ ...e, key: undefined })},`)
  .join('\n');

writeFileSync(
  out,
  `// Generated by scripts/gen-sources.mjs. Do not edit.\nimport type { PatternSource } from '../types/pattern';\n\nexport const patternSources: Record<string, PatternSource> = {\n${body}\n};\n`,
);

catalog.sort((a, b) => a.key.localeCompare(b.key));
const imports = catalog.flatMap((c) =>
  [
    `import { ${c.pattern} } from './${c.key}/pattern';`,
    c.transcript && `import { ${c.transcript} } from './${c.key}/transcript';`,
    c.walkthrough && `import { ${c.walkthrough} } from './${c.key}/walkthrough';`,
  ].filter(Boolean),
);
writeFileSync(
  catalogOut,
  [
    '// Generated by scripts/gen-sources.mjs. Do not edit.',
    "import type { PatternDefinition } from '../types/pattern';",
    "import type { ScreenReaderTranscript } from '../types/transcript';",
    "import type { CodeAnnotation } from '../types/walkthrough';",
    ...imports,
    '',
    `export const catalogPatterns: PatternDefinition[] = [${catalog.map((c) => c.pattern).join(', ')}];`,
    `export const catalogTranscripts: ScreenReaderTranscript[] = [${catalog.flatMap((c) => c.transcript ?? []).join(', ')}];`,
    `export const catalogWalkthroughs: Record<string, CodeAnnotation[]> = {${catalog
      .filter((c) => c.walkthrough)
      .map((c) => ` ${JSON.stringify(c.key)}: ${c.walkthrough}`)
      .join(',')} };`,
    '',
  ].join('\n'),
);
console.log(`gen-sources: wrote ${entries.length} pattern sources${client ? ' (client-scoped build)' : ''}`);
